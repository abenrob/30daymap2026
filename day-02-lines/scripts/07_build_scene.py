T.link(fac, trim.inputs[3])
rad = T.node("GeometryNodeSetCurveRadius", 600, 0)
T.link(trim.outputs[0], rad.inputs["Curve"])
rr_ = T.math("MULTIPLY_ADD", w, R_MAX - R_MIN, 400, -300)
