def attr(name, x, y):
    a = T.node("GeometryNodeInputNamedAttribute", x, y, data_type="FLOAT")
    a.inputs["Name"].default_value = name
    return a.outputs["Attribute"]

t0, t1, w = attr("t0", -400, -600), attr("t1", -400, -700), attr("w", -400, -800)
notyet = T.node("FunctionNodeCompare", 0, -500, data_type="FLOAT", operation="LESS_THAN")
T.link(gi.outputs["Clock"], notyet.inputs[0])
T.link(t0, notyet.inputs[1])
dele = T.node("GeometryNodeDeleteGeometry", 200, 0, domain="CURVE")
T.link(drape.outputs[0], dele.inputs["Geometry"])
T.link(notyet.outputs[0], dele.inputs["Selection"])
fac = T.math("DIVIDE", T.math("SUBTRACT", gi.outputs["Clock"], t0, 0, -700),
             T.math("SUBTRACT", t1, t0, 0, -800), 200, -700, clamp=True)
trim = T.node("GeometryNodeTrimCurve", 400, 0, mode="FACTOR")
T.link(dele.outputs[0], trim.inputs["Curve"])
