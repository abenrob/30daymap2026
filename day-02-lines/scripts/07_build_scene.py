rt, T, gi, go = gn_tree("Rivers", [("Clock", "NodeSocketFloat"), ("Terrain", "NodeSocketObject")])
oi = T.node("GeometryNodeObjectInfo", -1000, -400, transform_space="ORIGINAL")
T.link(gi.outputs["Terrain"], oi.inputs["Object"])
p = T.node("GeometryNodeInputPosition", -1000, -150)
src = T.node("ShaderNodeVectorMath", -800, -150, operation="ADD")
T.link(p.outputs[0], src.inputs[0])
src.inputs[1].default_value = (0, 0, 50)
ray = T.node("GeometryNodeRaycast", -600, -250)
