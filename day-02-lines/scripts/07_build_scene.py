# Orbit the camera a few degrees west of due south around the basin centre: the map turns
# counterclockwise in frame. DIST and HEIGHT set the tilt (about 43 degrees below horizontal).
# SHIFT_KM slides the aim point to the camera's left, which moves the map right in frame.
ORBIT, DIST, HEIGHT, SHIFT_KM, LENS = math.radians(-7), 560, 530, 28, 60
AX = CX - SHIFT_KM * math.cos(ORBIT)
AY = CY - 55 - SHIFT_KM * math.sin(ORBIT)
