"""Build the Blender scene for the Rhone animation (Blender 4.2+).

    blender -b -P site/day-02-lines/scripts/07_build_scene.py

Run from the workspace root after 06_anim_data.py. Saves work/blender/day-02-rhone.blend.
Inputs are linked by relative path from work/data/day-02-lines/blender/, so the .blend
stays small: the terrain is generated by Geometry Nodes from height.png at load time.

Scene units are kilometres, origin at the centre of the DEM extent, Lambert-93 axes.
One clock drives everything (network km, 0 to D_max), set by a driver on the frame:
  rivers  each piece draws from its upstream end at t0 to its downstream end at t1
  lakes   a pixel turns to water when the clock passes its time in lake_time.png
"""
import bpy, json, math, os
import numpy as np

ROOT = os.getcwd()
DATA = os.path.join(ROOT, "work/data/day-02-lines/blender")
BLEND = os.path.join(ROOT, "work/blender/day-02-rhone.blend")

EXAG = 3.0            # vertical exaggeration
DECIMATE = 2          # terrain mesh = DEM / DECIMATE per axis (2 -> 300 m, 2.7 M vertices)
FPS = 30
HOLD_IN, ANIM, HOLD_OUT = 30, 360, 90       # frames: still start, the flow, still end
R_MIN, R_MAX = 0.10, 1.1                    # river radius, km
LIFT = 0.04                                 # km above the terrain surface
TAPER_KM = 12.0       # terrain eases down to sea level over this distance from the DEM edge
FLAT_KM = 45.0        # and its shading fades to flat over this distance, so the edge disappears
EDGE = 6.0            # lake front softness, clock km
TEAL = (0.20, 0.95, 0.85, 1)
LAND_OUT = (0.018, 0.021, 0.026, 1)   # land outside the basin, and beyond the DEM
LAND_IN = (0.070, 0.078, 0.088, 1)    # land inside the basin
SEA = (0.004, 0.006, 0.009, 1)

meta = json.load(open(os.path.join(DATA, "meta.json")))
D_MAX = meta["d_max_km"]
WKM, HKM = meta["width_km"], meta["height_km"]
F0, F1 = HOLD_IN + 1, HOLD_IN + ANIM + 1
CLOCK_EXPR = f"max(0.0, min(1.0, (frame - {F0}) / {ANIM})) * {D_MAX:.3f}"

# ---------------------------------------------------------------- reset
bpy.ops.wm.read_factory_settings(use_empty=True)
scene = bpy.context.scene
scene.render.fps = FPS
scene.frame_start, scene.frame_end = 1, HOLD_IN + ANIM + HOLD_OUT
scene.unit_settings.system = "NONE"

def img(name):
    im = bpy.data.images.load(os.path.join(DATA, name), check_existing=True)
    im.colorspace_settings.name = "Non-Color"
    return im

def clock_driver(socket_owner, path, index=-1):
    fc = socket_owner.driver_add(path, index) if index >= 0 else socket_owner.driver_add(path)
    fc.driver.type = "SCRIPTED"
    fc.driver.expression = CLOCK_EXPR
    return fc

class Tree:
    """Tiny helper for building node trees in code."""
    def __init__(self, tree):
        self.t, self.n, self.l = tree, tree.nodes, tree.links
    def node(self, kind, x=0, y=0, **props):
        nd = self.n.new(kind)
        nd.location = (x, y)
        for k, v in props.items():
            setattr(nd, k, v)
        return nd
    def link(self, a, b):
        self.l.new(a, b)
    def math(self, op, a, b=None, x=0, y=0, clamp=False):
        m = self.node("ShaderNodeMath", x, y, operation=op, use_clamp=clamp)
        for i, v in enumerate([a, b]):
            if v is None:
                continue
            if isinstance(v, (int, float)):
                m.inputs[i].default_value = v
            else:
                self.link(v, m.inputs[i])
        return m.outputs[0]

def gn_tree(name, inputs=()):
    t = bpy.data.node_groups.new(name, "GeometryNodeTree")
    t.interface.new_socket("Geometry", in_out="INPUT", socket_type="NodeSocketGeometry")
    for nm, kind in inputs:
        t.interface.new_socket(nm, in_out="INPUT", socket_type=kind)
    t.interface.new_socket("Geometry", in_out="OUTPUT", socket_type="NodeSocketGeometry")
    T = Tree(t)
    gi, go = T.node("NodeGroupInput", -1200, 0), T.node("NodeGroupOutput", 1400, 0)
    return t, T, gi, go

# ---------------------------------------------------------------- terrain material
mt = bpy.data.materials.new("Terrain")
mt.use_nodes = True
S = Tree(mt.node_tree)
bsdf = S.n["Principled BSDF"]
bsdf.inputs["Roughness"].default_value = 1.0
bsdf.inputs["Specular IOR Level"].default_value = 0.0
uv = S.node("ShaderNodeAttribute", -900, 0, attribute_name="UVMap")
masks = S.node("ShaderNodeTexImage", -700, 0, image=img("masks.png"), interpolation="Linear")
S.link(uv.outputs["Vector"], masks.inputs["Vector"])
sep = S.node("ShaderNodeSeparateColor", -450, 0)
S.link(masks.outputs["Color"], sep.inputs["Color"])
land = S.node("ShaderNodeMix", -250, 100, data_type="RGBA")
land.inputs[6].default_value = LAND_OUT
land.inputs[7].default_value = LAND_IN
S.link(sep.outputs["Red"], land.inputs[0])
sea = S.node("ShaderNodeMix", -50, 100, data_type="RGBA")
sea.inputs[7].default_value = SEA
S.link(land.outputs[2], sea.inputs[6])
S.link(sep.outputs["Green"], sea.inputs[0])
S.link(sea.outputs[2], bsdf.inputs["Base Color"])
# near the DEM edge the shading normal blends to straight up, matching the flat ground plane
relief = S.node("ShaderNodeAttribute", -450, -350, attribute_name="relief")
geo = S.node("ShaderNodeNewGeometry", -450, -550)
nmix = S.node("ShaderNodeMix", -200, -400, data_type="VECTOR")
S.link(relief.outputs["Fac"], nmix.inputs[0])
S.link(geo.outputs["Normal"], nmix.inputs[5])
nmix.inputs[4].default_value = (0, 0, 1)
S.link(nmix.outputs[1], bsdf.inputs["Normal"])

# ---------------------------------------------------------------- terrain (Geometry Nodes)
tt, T, gi, go = gn_tree("Terrain")
nx, ny = meta["dem_px"][0] // DECIMATE, meta["dem_px"][1] // DECIMATE
grid = T.node("GeometryNodeMeshGrid", -900, 0)
grid.inputs["Size X"].default_value = WKM
grid.inputs["Size Y"].default_value = HKM
grid.inputs["Vertices X"].default_value = nx
grid.inputs["Vertices Y"].default_value = ny
tex = T.node("GeometryNodeImageTexture", -600, -200, interpolation="Linear")
tex.inputs["Image"].default_value = img("height.png")
T.link(grid.outputs["UV Map"], tex.inputs["Vector"])
zmin, zmax = meta["z_min_m"], meta["z_max_m"]
zkm = T.math("MULTIPLY_ADD", tex.outputs["Color"], (zmax - zmin) / 1000 * EXAG, -400, -200)
zkm.node.inputs[2].default_value = zmin / 1000 * EXAG
# ease the terrain to sea level near the DEM edge, so it meets the ground plane without a cliff
uvs = T.node("ShaderNodeSeparateXYZ", -900, -500)
T.link(grid.outputs["UV Map"], uvs.inputs[0])
def edge_km(c, size, y):
    return T.math("MULTIPLY", T.math("MINIMUM", c, T.math("SUBTRACT", 1.0, c, -700, y), -550, y), size, -400, y)
d = T.math("MINIMUM", edge_km(uvs.outputs["X"], WKM, -500), edge_km(uvs.outputs["Y"], HKM, -650), -250, -550)
ease = T.node("ShaderNodeMapRange", -100, -550, interpolation_type="SMOOTHSTEP")
T.link(d, ease.inputs["Value"])
ease.inputs["From Min"].default_value, ease.inputs["From Max"].default_value = 0.0, TAPER_KM
zt = T.math("MULTIPLY", zkm, ease.outputs[0], -200, -300)
shade = T.node("ShaderNodeMapRange", -100, -750, interpolation_type="SMOOTHSTEP")
T.link(d, shade.inputs["Value"])
shade.inputs["From Min"].default_value, shade.inputs["From Max"].default_value = 0.0, FLAT_KM
off = T.node("ShaderNodeCombineXYZ", -200, -200)
T.link(zt, off.inputs["Z"])
setp = T.node("GeometryNodeSetPosition", 0, 0)
T.link(grid.outputs["Mesh"], setp.inputs["Geometry"])
T.link(off.outputs[0], setp.inputs["Offset"])
store = T.node("GeometryNodeStoreNamedAttribute", 250, 0, data_type="FLOAT2", domain="CORNER")
store.inputs["Name"].default_value = "UVMap"
T.link(setp.outputs[0], store.inputs["Geometry"])
T.link(grid.outputs["UV Map"], store.inputs["Value"])
store_e = T.node("GeometryNodeStoreNamedAttribute", 400, 0, data_type="FLOAT", domain="POINT")
store_e.inputs["Name"].default_value = "relief"
T.link(store.outputs[0], store_e.inputs["Geometry"])
T.link(shade.outputs[0], store_e.inputs["Value"])
smooth = T.node("GeometryNodeSetShadeSmooth", 500, 0)
T.link(store_e.outputs[0], smooth.inputs["Geometry"])
smat = T.node("GeometryNodeSetMaterial", 750, 0)
smat.inputs["Material"].default_value = mt
T.link(smooth.outputs[0], smat.inputs["Geometry"])
T.link(smat.outputs[0], go.inputs[0])

terrain = bpy.data.objects.new("Terrain", bpy.data.meshes.new("Terrain"))
scene.collection.objects.link(terrain)
terrain.modifiers.new("Terrain", "NODES").node_group = tt

# ---------------------------------------------------------------- rivers (Curves + GN)
r = np.load(os.path.join(DATA, "rivers.npz"))
offs = r["offsets"]
sizes = np.diff(offs).astype(int)
cv = bpy.data.hair_curves.new("Rivers")
