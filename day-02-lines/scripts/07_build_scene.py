T.link(oi.outputs["Geometry"], ray.inputs["Target Geometry"])
T.link(src.outputs[0], ray.inputs["Source Position"])
lift = T.node("ShaderNodeVectorMath", -400, -250, operation="ADD")
T.link(ray.outputs["Hit Position"], lift.inputs[0])
lift.inputs[1].default_value = (0, 0, LIFT)
